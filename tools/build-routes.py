#!/usr/bin/env python3
"""Writes the stub pages that give each view a real URL, plus sitemap.xml.

Why: the site is one page (index.html) that swaps views with JavaScript.
GitHub Pages only serves files, so /about needs an about/index.html to exist.
Each stub has its own title and link-preview tags (what LinkedIn or Slack shows
when you paste the link), then sends the browser to /?route=/about, where
js/router.js opens the right view.

Run it from the repo root after adding or renaming a case study:
    python3 tools/build-routes.py

Case study names and descriptions come from the stations in index.html
(<article class="stop" id="...">), so there is nothing to keep in sync by hand.
"""
import html
import re
from datetime import date
from pathlib import Path

SITE = "https://jesscummingsportfolio.com"
ROOT = Path(__file__).resolve().parent.parent
NAME = "Jess Cummings"
PRIVATE = {"constrat"}          # password protected: kept out of search engines and the sitemap

STUB = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<!-- Generated by tools/build-routes.py. Edit that script, not this file. -->
<title>{title}</title>
<meta name="description" content="{desc}">
<link rel="canonical" href="{url}">
{robots}<meta property="og:type" content="website">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{desc}">
<meta property="og:url" content="{url}">
<meta property="og:image" content="{site}/og-image.jpg">
<meta name="twitter:card" content="summary_large_image">
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>body{{margin:0;background:#111;color:#f4f4f2;font-family:"Helvetica Neue",Helvetica,Arial,sans-serif}}a{{color:#FCCC0A}}</style>
<script>
  // Hand the path to the real page; js/router.js puts it back in the address bar.
  var q = location.search ? "&" + location.search.slice(1) : "";
  location.replace("/?route=" + encodeURIComponent("{path}") + q + location.hash);
</script>
</head>
<body>
<noscript><p><a href="/">{title}</a>: this site needs JavaScript to open this page.</p></noscript>
</body>
</html>
"""


def stations():
    """Each case study station on the home page: (id, headline, description)."""
    page = (ROOT / "index.html").read_text()
    pattern = r'<article class="stop" id="([\w-]+)".*?<span class="pill">(.*?)</span>.*?<p class="desc">(.*?)</p>'
    for m in re.finditer(pattern, page, re.S):
        yield m.group(1), html.unescape(m.group(2)), html.unescape(m.group(3))


def routes():
    yield "/about", f"About · {NAME}", "How Jess Cummings designs: a product designer in Detroit who designs complex B2B systems."
    yield "/play", f"Play · {NAME}", "Made for fun: Jess Cummings' side projects, hackathons and tools."
    for cid, name, desc in stations():
        yield f"/work/{cid}", f"{name} case study · {NAME}", desc


def main():
    sitemap = [("/", "1.0"), ("/JessCummings_Resume.pdf", "0.7")]
    for path, title, desc in routes():
        private = path.rsplit("/", 1)[-1] in PRIVATE
        out = ROOT / path.strip("/") / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(STUB.format(
            title=html.escape(title), desc=html.escape(desc), path=path, site=SITE, url=SITE + path,
            robots='<meta name="robots" content="noindex">\n' if private else ""))
        print("wrote", out.relative_to(ROOT))
        if not private:
            sitemap.append((path, "0.8"))

    today = date.today().isoformat()
    urls = "\n".join(f"  <url><loc>{SITE}{p}</loc><lastmod>{today}</lastmod><priority>{pr}</priority></url>" for p, pr in sitemap)
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls + "\n</urlset>\n")
    print("wrote sitemap.xml")


if __name__ == "__main__":
    main()
